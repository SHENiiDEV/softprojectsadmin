#!/usr/bin/env bash
#
# Refresh Cloudflare IP ranges (see DEPLOY.md, "Cloudflare").
#   ./cloudflare-ips.sh          nginx: restore real client IP (CF-Connecting-IP) for requests coming from Cloudflare
#   ./cloudflare-ips.sh --ufw    additionally allow port 443 only from Cloudflare (port 80 stays open for certbot)
#
# Run as root. Safe to re-run (cron: monthly).
set -euo pipefail

SNIPPET=/etc/nginx/snippets/cloudflare-realip.conf
IPS_V4_URL=https://www.cloudflare.com/ips-v4
IPS_V6_URL=https://www.cloudflare.com/ips-v6

ranges_v4=$(curl -fsS "$IPS_V4_URL")
ranges_v6=$(curl -fsS "$IPS_V6_URL")

# Never continue with an empty/garbled list (would lock the site out or trust nobody)
if ! grep -qE '^[0-9.]+/[0-9]+$' <<<"$ranges_v4" || ! grep -qE '^[0-9a-fA-F:]+/[0-9]+$' <<<"$ranges_v6"; then
    echo "Unexpected response from Cloudflare, aborting." >&2
    exit 1
fi

mkdir -p "$(dirname "$SNIPPET")"
tmp=$(mktemp)
{
    echo "# Generated by cloudflare-ips.sh on $(date -u +%F) - do not edit"
    for ip in $ranges_v4 $ranges_v6; do
        echo "set_real_ip_from $ip;"
    done
    echo "real_ip_header CF-Connecting-IP;"
    echo "real_ip_recursive on;"
} >"$tmp"
install -m 644 "$tmp" "$SNIPPET"
rm -f "$tmp"

nginx -t
systemctl reload nginx
echo "nginx real-IP snippet updated: $SNIPPET"

if [[ "${1:-}" == "--ufw" ]]; then
    # Keep 80 open (Let's Encrypt HTTP-01 renewals do not come from Cloudflare)
    ufw allow 80/tcp comment 'http (certbot)' >/dev/null

    # Drop previous Cloudflare rules
    while rule=$(ufw status numbered | grep -m1 'cloudflare' | sed -E 's/^\[ *([0-9]+)\].*/\1/'); [[ -n "$rule" ]]; do
        ufw --force delete "$rule" >/dev/null
    done

    for ip in $ranges_v4 $ranges_v6; do
        ufw allow from "$ip" to any port 443 proto tcp comment 'cloudflare' >/dev/null
    done

    # Remove the blanket 80+443 rule only after the Cloudflare rules exist
    ufw delete allow "Nginx Full" >/dev/null 2>&1 || true
    ufw reload >/dev/null
    echo "ufw: 443 restricted to Cloudflare, 80 open for certbot"
fi
